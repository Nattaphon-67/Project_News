async function seedNews() {
  try {
    const count = await News.count();
    if (count === 0) {
      await News.bulkCreate(initialNewsData);
      console.log(`✅ เพิ่มข้อมูลข่าวเริ่มต้น ${initialNewsData.length} รายการเรียบร้อยแล้ว`);
    } else if (count < initialNewsData.length) {
      // เพิ่มเฉพาะรายการข่าวใหม่ที่ยังไม่มีในฐานข้อมูล
      const existingTitles = (await News.findAll({ attributes: ["title"] })).map((n) => n.title);
      const newItems = initialNewsData.filter((item) => !existingTitles.includes(item.title));
      if (newItems.length > 0) {
        await News.bulkCreate(newItems);
        console.log(`✅ เพิ่มข้อมูลข่าวใหม่เพิ่มเติมอีก ${newItems.length} รายการเรียบร้อยแล้ว (รวมทั้งหมด ${count + newItems.length} รายการ)`);
      }
    } else {
      console.log(`ℹ️ มีข้อมูลในตาราง news ครบแล้ว (${count} รายการ) ไม่ต้องใส่ Seed Data เพิ่ม`);
    }
  } catch (error) {
    console.error("❌ เกิดข้อผิดพลาดในการใส่ Seed Data:", error);
  }
}

module.exports = seedNews;
